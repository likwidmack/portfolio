#!/usr/bin/env node
/**
 * Regenerate `scss/tokens/_variations.generated.scss` from `buildColorVariations()`, which
 * derives every `--theme-<colour>-<variation>-color` default from `colors.json` sass sources and
 * `DEFAULT_PAPER_INK` (plus `--theme-button-fg-dark-color` from `buildButtonInkTokens()` and
 * `--theme-primary-fill-{light,dark}-color` from `buildPrimaryFillTokens()` and
 * `--theme-primary-ink-{light,dark}-color` from `buildPrimaryInkTokens()` and
 * `--theme-secondary-ink-{light,dark}-color` from `buildSecondaryInkTokens()` and
 * `--theme-<status>-ink-{light,dark}-color` from `buildStatusInkTokens()` and
 * `--theme-{primary,secondary}-wash-{light,dark}-color` from `buildWashTokens()` and
 * `--theme-link-{light,dark}-color` from `buildLinkTokens()` and the solid-button gradient stops
 * `--theme-{secondary-fill,secondary-inverted,primary-sheen}-{light,dark}-color` from
 * `buildButtonStopTokens()`, plus `$theme-wash-alpha`). Run after a solid colour source or the paper/ink defaults change:
 *
 *   npm run build:variations --workspace=@tgmc/theme
 *
 * It compiles the library first (the builder is TypeScript), then writes the Sass partial sorted
 * and lowercase so a no-op run leaves the file unchanged.
 * `tests/color-variations.spec.ts` fails when the committed partial drifts from the builder.
 *
 * (Until colour system Task 8 it also wrote the old-name alias partial; the aliases are gone —
 * archived in `scss/_archive/2026-09-29-color-aliases/`.)
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const {
  buildButtonInkTokens,
  buildButtonStopTokens,
  buildColorVariations,
  buildLinkTokens,
  buildPrimaryFillTokens,
  buildPrimaryInkTokens,
  buildSecondaryInkTokens,
  buildStatusInkTokens,
  buildWashTokens,
  DEFAULT_COLOR_SOURCES,
  SOLID_COLORS,
  WASH_ALPHA,
} = await import(pathToFileURL(join(root, 'dist', 'color-variations.js')).href);
const { DEFAULT_PAPER_INK } = await import(pathToFileURL(join(root, 'dist', 'paper-ink.js')).href);
const target = join(root, 'scss', 'tokens', '_variations.generated.scss');

const variations = buildColorVariations(DEFAULT_COLOR_SOURCES, DEFAULT_PAPER_INK);
// Plus the per-mode button text for each primary variation (`--theme-button-fg-color` points at the active one).
// and the white-text primary fill per mode (light-mode primary buttons paint it),
// and the text-contrast primary / secondary / status inks per mode (`--theme-{primary,secondary}-ink-color` point at the active one).
const primaryInk = buildPrimaryInkTokens(DEFAULT_COLOR_SOURCES, DEFAULT_PAPER_INK);
const vars = {
  ...variations,
  ...buildButtonInkTokens(variations),
  ...buildPrimaryFillTokens(variations),
  ...primaryInk,
  ...buildSecondaryInkTokens(DEFAULT_COLOR_SOURCES, DEFAULT_PAPER_INK),
  ...buildStatusInkTokens(DEFAULT_COLOR_SOURCES, DEFAULT_PAPER_INK),
  // and the hover / active washes under primary-ink text (`--theme-{primary,secondary}-wash-color`).
  ...buildWashTokens(variations, primaryInk, DEFAULT_PAPER_INK),
  // and the link ink (`--theme-link-color`) and the solid-button gradient stops.
  ...buildLinkTokens(DEFAULT_COLOR_SOURCES, DEFAULT_PAPER_INK),
  ...buildButtonStopTokens(variations),
};
const entries = Object.entries(vars).sort(([a], [b]) => a.localeCompare(b));
const lines = entries.map(([name, hex]) => `$${name.slice(2)}: ${hex};`);

// A Sass map alongside the flat variables, keyed by colour, so `globals/_root.scss` can emit the
// eight solid colours with one `@each` loop instead of naming every variable by hand.
const mapLines = SOLID_COLORS.map(
  (c) =>
    `  ${c}: (\n` +
    `    light: $theme-${c}-light-color,\n` +
    `    dark: $theme-${c}-dark-color,\n` +
    `    light-background: $theme-${c}-light-background-color,\n` +
    `    dark-background: $theme-${c}-dark-background-color,\n` +
    `  ),`
).join('\n');
const map = `\n$theme-variations: (\n${mapLines}\n);\n`;

// The alpha the stylesheet paints the hover / active washes at (`WASH_ALPHA`).
const alpha = `\n$theme-wash-alpha: ${Math.round(WASH_ALPHA * 100)}%;\n`;
const output = `// GENERATED by bin/build-color-variations.mjs — do not edit.\n${lines.join('\n')}\n${map}${alpha}`;
writeFileSync(target, output);
console.log(`Wrote ${target} (${lines.length} variables)`);
